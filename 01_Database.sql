-- IMPORTING THE DATA IN THE RAW TABLES INTO CLEAN TABLES
DROP TABLE IF EXISTS applicants, bureau_history;

CREATE TABLE applicants AS
SELECT
    SK_ID_CURR::NUMERIC::INT AS sk_id_curr,
    NULLIF(TARGET, '')::NUMERIC::INT AS target,
    NAME_CONTRACT_TYPE AS contract_type,
    CODE_GENDER AS gender,
    FLAG_OWN_CAR AS owns_car,
    FLAG_OWN_REALTY AS owns_realty,
    NULLIF(CNT_CHILDREN, '')::NUMERIC::INT AS cnt_children,
    NULLIF(AMT_INCOME_TOTAL, '')::NUMERIC AS income_total,
    NULLIF(AMT_CREDIT, '')::NUMERIC AS credit_amount,
    NULLIF(AMT_ANNUITY, '')::NUMERIC AS annuity_amount,
    NULLIF(AMT_GOODS_PRICE, '')::NUMERIC AS goods_price,
    NAME_INCOME_TYPE AS income_type,
    NAME_EDUCATION_TYPE AS education_type,
    NAME_FAMILY_STATUS AS family_status,
    NAME_HOUSING_TYPE AS housing_type,
    ROUND(ABS(NULLIF(DAYS_BIRTH, '')::NUMERIC) / 365, 1) AS age_years,
    CASE
        WHEN NULLIF(DAYS_EMPLOYED, '')::NUMERIC = 365243 THEN NULL
        ELSE ROUND(ABS(NULLIF(DAYS_EMPLOYED, '')::NUMERIC) / 365, 1)
    END AS years_employed,
    OCCUPATION_TYPE AS occupation_type,
    NULLIF(CNT_FAM_MEMBERS, '')::NUMERIC::INT AS cnt_family_members,
    ORGANIZATION_TYPE AS organization_type,
    NULLIF(EXT_SOURCE_1, '')::NUMERIC AS ext_source_1,
    NULLIF(EXT_SOURCE_2, '')::NUMERIC AS ext_source_2,
    NULLIF(EXT_SOURCE_3, '')::NUMERIC AS ext_source_3
FROM raw_applicants;

CREATE TABLE bureau_history AS
SELECT
    SK_ID_BUREAU::NUMERIC::INT AS sk_id_bureau,
    SK_ID_CURR::NUMERIC::INT AS sk_id_curr,
    CREDIT_ACTIVE AS credit_active,
    CREDIT_TYPE AS credit_type,
    ROUND(ABS(NULLIF(DAYS_CREDIT, '')::NUMERIC) / 365, 1) AS years_since_credit_opened,
    ROUND(NULLIF(DAYS_CREDIT_ENDDATE, '')::NUMERIC / 365, 1) AS years_to_credit_end,
    ROUND(ABS(NULLIF(DAYS_ENDDATE_FACT, '')::NUMERIC) / 365, 1) AS years_since_credit_closed,
    NULLIF(CREDIT_DAY_OVERDUE, '')::NUMERIC::INT AS days_overdue,
    NULLIF(CNT_CREDIT_PROLONG, '')::NUMERIC::INT AS times_prolonged,
    NULLIF(AMT_CREDIT_SUM, '')::NUMERIC AS credit_sum,
    GREATEST(COALESCE(NULLIF(AMT_CREDIT_SUM_DEBT, '')::NUMERIC, 0), 0) AS credit_sum_debt,
    NULLIF(AMT_CREDIT_SUM_LIMIT, '')::NUMERIC AS credit_sum_limit,
    NULLIF(AMT_CREDIT_SUM_OVERDUE, '')::NUMERIC AS credit_sum_overdue,
    NULLIF(AMT_CREDIT_MAX_OVERDUE, '')::NUMERIC AS max_overdue_ever,
    NULLIF(AMT_ANNUITY, '')::NUMERIC AS annuity_amount
FROM raw_bureau;


